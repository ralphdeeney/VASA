from collections.abc import AsyncIterator
from contextlib import AbstractAsyncContextManager
from typing import Any, Protocol

from vasa.contracts.models import (
    AudioFrame,
    ConnectionStatus,
    IncomingCall,
    PairingQR,
    TenantContext,
)


class MediaConnection(Protocol):
    async def receive(self) -> AudioFrame | None: ...
    async def send(self, frame: AudioFrame) -> None: ...
    async def close(self) -> None: ...


class EvolutionClient(Protocol):
    """Verified Wave 2 boundary; no upstream endpoints or credentials reach consumers."""

    async def create_instance(self, instance_id: str, name: str) -> None: ...
    async def delete_instance(self, instance_id: str) -> None: ...
    async def connect(self, instance_id: str) -> None: ...
    async def disconnect(self, instance_id: str) -> None: ...
    async def status(self, instance_id: str) -> ConnectionStatus: ...
    async def qr(self, instance_id: str) -> PairingQR: ...
    async def answer(self, instance_id: str, call_id: str, caller_jid: str) -> None: ...
    async def reject(self, instance_id: str, call_id: str, caller_jid: str) -> None: ...
    async def hangup(self, instance_id: str, call_id: str) -> None: ...
    def open_media(
        self, instance_id: str, call_id: str
    ) -> AbstractAsyncContextManager[MediaConnection]: ...
    def events(self, instance_id: str) -> AsyncIterator[IncomingCall]: ...


class STTProvider(Protocol):
    def transcribe(self, frames: AsyncIterator[AudioFrame]) -> AsyncIterator[str]: ...


class TTSProvider(Protocol):
    def synthesize(self, text: str) -> AsyncIterator[AudioFrame]: ...


class LLMProvider(Protocol):
    def respond(
        self, context: TenantContext, messages: list[dict[str, str]]
    ) -> AsyncIterator[dict[str, Any]]: ...


class Tool(Protocol):
    name: str

    async def execute(
        self, context: TenantContext, arguments: dict[str, Any]
    ) -> dict[str, Any]: ...
